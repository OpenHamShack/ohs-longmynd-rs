#!/usr/bin/env python3
"""Generate src/regs/*.rs from longmynd's register headers.

About half of longmynd's 12.6k lines are register tables: every STV0910
register and bitfield (stv0910_regs.h, from ST via Digital Devices), the
STV0910 power-on table longmynd writes at every init (stv0910_regs_init.h),
and the STV6120 tuner and STVVGLNA LNA definitions. A port that retyped
those by hand would be a port with a typo in it somewhere nobody looks, so
they are translated mechanically, from the reference tree, by this script.

Usage: tools/gen-regs.py <longmynd source dir> <output dir>
       (tools/gen-regs.sh does the extract-and-patch and calls this.)

The translation is deliberately dumb: every `#define NAME <integer>` becomes
a `pub const`, typed by what the C does with it, and the init table keeps the
C's order and the register *names*, so the generated file reads like the
header. Anything the script does not recognise stops it, rather than being
skipped: a skipped define would surface as a missing constant at best and a
missing register write at worst.
"""
import re
import sys
from pathlib import Path

DEFINE = re.compile(r'^\s*#\s*define\s+(\w+)\s+(0x[0-9a-fA-F]+|[0-9]+)\s*$')
GUARD = re.compile(r'^\s*#\s*(define\s+\w+_H|ifndef\s+\w+_H|endif)\s*$')
INIT_ENTRY = re.compile(r'\{\s*(RSTV0910_\w+)\s*,\s*(0x[0-9a-fA-F]+)\s*\}')


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'//[^\n]*', ' ', text)


def defines(path):
    out = []
    seen = {}
    for n, line in enumerate(strip_comments(path.read_text()).splitlines(), 1):
        if not line.strip() or GUARD.match(line):
            continue
        m = DEFINE.match(line)
        if m:
            name, value = m.group(1), int(m.group(2), 0)
            # C allows an identical redefinition (stv6120_regs.h defines
            # CTRL9 twice); Rust does not, and a different one is a bug.
            if name in seen:
                if seen[name] != value:
                    sys.exit(f"{path.name}:{n}: {name} redefined with a different value")
                continue
            seen[name] = value
            out.append((name, value, m.group(2)))
        elif line.strip().startswith('#'):
            sys.exit(f"{path.name}: unrecognised preprocessor line: {line.strip()}")
    return out


def header(src):
    return (f"// GENERATED by tools/gen-regs.py from longmynd's {src} - do not edit.\n"
            "// Copyright 2019 Heather Lomond; STV0910 definitions (c) 2013 Digital Devices GmbH.\n"
            "// Part of longmynd-rs, GPLv3 (see LICENSE).\n"
            "#![allow(dead_code)]\n\n")


def stv0910_type(name, value):
    # Registers are 16-bit addresses; fields pack address, shift, sign and
    # mask into 32 bits (stv0910_regs.h explains the layout); NBREGS and
    # NBFIELDS are counts (NBREGS sizes the C init array).
    if name.startswith('RSTV0910_'):
        return 'u16'
    if name.startswith('FSTV0910_'):
        return 'u32'
    if name in ('STV0910_NBREGS', 'STV0910_NBFIELDS'):
        return 'usize'
    sys.exit(f"stv0910_regs.h: no type rule for {name}")


def gen_stv0910(src, out):
    defs = defines(src / 'stv0910_regs.h')
    lines = [header('stv0910_regs.h')]
    for name, value, text in defs:
        t = stv0910_type(name, value)
        lines.append(f"pub const {name}: {t} = {text};\n")
    (out / 'stv0910_regs.rs').write_text(''.join(lines))
    return {name for name, _, _ in defs}


def gen_init(src, out, known):
    text = strip_comments((src / 'stv0910_regs_init.h').read_text())
    body = text[text.index('STV0910DefVal'):]
    body = body[body.index('{') + 1:body.rindex('}')]
    entries = INIT_ENTRY.findall(body)
    leftover = INIT_ENTRY.sub('', body).replace(',', '').strip()
    if leftover:
        sys.exit(f"stv0910_regs_init.h: unparsed text in the table: {leftover[:80]!r}")
    for name, _ in entries:
        if name not in known:
            sys.exit(f"stv0910_regs_init.h: {name} is not in stv0910_regs.h")
    if [n for n, _ in entries].index('RSTV0910_TSTTSRS') != len(entries) - 1:
        # stv0910_init_regs() writes entries until it has written TSTTSRS;
        # one that held it earlier would stop there in C, and the Rust walks
        # the whole table.
        sys.exit("stv0910_regs_init.h: RSTV0910_TSTTSRS must be the last entry, and only there")
    lines = [header('stv0910_regs_init.h'),
             "use super::stv0910_regs::*;\n\n",
             "/// The STV0910 register defaults longmynd writes at every init, in its\n"
             "/// order (stv0910_init_regs walks the C array up to RSTV0910_TSTTSRS).\n",
             f"pub static STV0910_DEF_VAL: [(u16, u8); {len(entries)}] = [\n"]
    for name, val in entries:
        lines.append(f"    ({name}, {val}),\n")
    lines.append("];\n")
    (out / 'stv0910_regs_init.rs').write_text(''.join(lines))


def gen_small(src, out, hname, rsname):
    # STV6120 and STVVGLNA definitions are register numbers, shifts, masks
    # and field values, all byte-sized; u8 is what the C stores them in.
    defs = defines(src / hname)
    lines = [header(hname)]
    for name, value, text in defs:
        if value > 0xff:
            sys.exit(f"{hname}: {name}={text} does not fit the u8 every other definition is")
        lines.append(f"pub const {name}: u8 = {text};\n")
    (out / rsname).write_text(''.join(lines))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    known = gen_stv0910(src, out)
    gen_init(src, out, known)
    gen_small(src, out, 'stv6120_regs.h', 'stv6120_regs.rs')
    gen_small(src, out, 'stvvglna_regs.h', 'stvvglna_regs.rs')


if __name__ == '__main__':
    main()
